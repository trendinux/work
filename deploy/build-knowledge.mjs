// Builds src/knowledge.js from the résumé and the case-study pages, so the
// assistant can only draw on what the portfolio itself says.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const site = join(here, "..");
const PER_PROJECT_CHARS = 2400;

const decode = (s) =>
  s
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&rsquo;|&lsquo;/g, "'")
    .replace(/&rdquo;|&ldquo;/g, '"')
    .replace(/&mdash;/g, "-")
    .replace(/&ndash;/g, "-")
    .replace(/&hellip;/g, "...")
    .replace(/&#(\d+);/g, (_, n) => String.fromCharCode(Number(n)))
    .replace(/&[a-z]+;/g, " ");

function pageText(html) {
  const body = html.split(/<\/head>/i)[1] ?? html;
  return decode(
    body
      .replace(/<(script|style|svg|nav|footer|aside)[\s\S]*?<\/\1>/gi, " ")
      .replace(/<(h1|h2|h3|p|li|figcaption|dt|dd)[^>]*>/gi, "\n")
      .replace(/<[^>]+>/g, " "),
  )
    .split("\n")
    .map((line) => line.replace(/\s+/g, " ").trim())
    .filter((line) => line.length > 2)
    .join("\n");
}

const projects = readdirSync(join(site, "projects"))
  .filter((f) => f.endsWith(".html"))
  .sort()
  .map((file) => {
    const html = readFileSync(join(site, "projects", file), "utf8");
    const title = (html.match(/<title>([^<]+)<\/title>/i)?.[1] ?? file)
      .replace(/\s*(?:[—|-])\s*Jonathan Lu\s*$/, "")
      .trim();
    const description = decode(
      html.match(/<meta name="description" content="([^"]*)"/i)?.[1] ?? "",
    );
    return {
      slug: file.replace(/\.html$/, ""),
      title: decode(title),
      path: `/projects/${file}`,
      text: `${description}\n${pageText(html)}`.slice(0, PER_PROJECT_CHARS),
    };
  });

const resume = readFileSync(join(here, "knowledge", "resume.md"), "utf8").trim();

const out = `// Generated by build-knowledge.mjs. Do not edit; rerun the script.
export const RESUME = ${JSON.stringify(resume)};
export const PROJECTS = ${JSON.stringify(projects, null, 1)};
`;
writeFileSync(join(here, "src", "knowledge.js"), out);
const chars = resume.length + projects.reduce((n, p) => n + p.text.length, 0);
console.log(`knowledge.js: ${projects.length} case studies, ${chars} characters`);
